"""
Meissa-4B inference backend.

Meissa-4B is fine-tuned from Qwen3-VL-4B using SFT trajectories generated by
a teacher model (Gemini/large VLM). Its output format differs from the base
Qwen3-VL-4B in two ways:

  1. Tool calls: bare JSON after a <think> block, NOT <tool_call> XML:
       <think>reasoning</think>{"name": "BioMedParseTextSeg", "arguments": {...}}

  2. Final answer: [FINAL] prefix, NOT Terminate JSON:
       <think>reasoning</think>[FINAL] yes

  3. System prompt: must match the one used during SFT (from evaluator.py).

This class:
  - Loads weights identically to qwen3vl.py (same architecture)
  - Overrides the system prompt injected by dynamic_batch_manager
  - Adds a <think>-block stripper in generate_conversation_fn so the
    observation turn passed back to the model is clean

Usage:
    python -m tool_server.tf_eval \\
      --model meissa \\
      --model_args "pretrained=/path/to/Meissa-4B,torch_dtype=auto,device_map=auto" \\
      --task_name pathvqa --max_rounds 5 ...
"""

from .abstract_model import tp_model

import re
import uuid
from PIL import Image
from typing import List

from ..utils.utils import *
from ..tool_inferencer.dynamic_batch_manager import DynamicBatchItem
from ..utils.log_utils import get_logger

logger = get_logger("meissa_model")

# System prompt that matches what was used to generate the SFT training data.
# Must stay in sync with evaluator.py's convert_to_sft_format system_prompt.
MEISSA_SYSTEM_PROMPT = (
    "You are a visual assistant for medical images. "
    "Your goal is to answer correctly by deciding whether to use tools.\n"
    "--------------------------------------------------\n"
    "IMAGE REFERENCE PROTOCOL\n"
    "--------------------------------------------------\n"
    '- "img_original": The initial full-resolution input image.\n'
    '- "img_last": The output image from the immediate previous step (default).\n'
    '- "img_round_N": The output image from a specific past step N (e.g. "img_round_0").\n'
    "The system will explicitly tell you the ID of the generated image in the Observation "
    '(e.g. "[Output Image ID: img_round_0]").\n'
    "--------------------------------------------------\n"
    "THINKING PROCESS\n"
    "--------------------------------------------------\n"
    "You possess an internal chain of thought. Before taking any action (calling a tool) "
    "or giving a final answer, you MUST enclose your reasoning, planning, and reflection "
    "process within <think> and </think> tags.\n"
    "--------------------------------------------------\n"
    "TOOL USE\n"
    "--------------------------------------------------\n"
    "If you need external information to answer the question, generate a function call.\n"
    "1. Analyze the current state in your <think> block.\n"
    "2. Call the appropriate tool with precise arguments.\n"
    "   Output the call as a JSON object on a new line: "
    '{"name": "<tool_name>", "arguments": {"image": "<img_ref>", "param": "<value>"}}\n'
    "3. Review the observation in your next <think> block.\n"
    "--------------------------------------------------\n"
    "FINAL ANSWER\n"
    "--------------------------------------------------\n"
    "When you have sufficient information, output [FINAL] followed by the answer."
)


def _strip_think_blocks(text: str) -> str:
    """Remove <think>...</think> blocks from model output."""
    return re.sub(r"<think>.*?</think>", "", text, flags=re.DOTALL).strip()


class MeissaModel(tp_model):
    def __init__(
        self,
        pretrained: str = None,
        torch_dtype: str = "auto",
        device_map: str = "auto",
        trust_remote_code: bool = True,
        **kwargs,
    ):
        try:
            from transformers import AutoModelForCausalLM, AutoProcessor
        except ImportError:
            from transformers import AutoModelForVision2Seq as AutoModelForCausalLM
            from transformers import AutoProcessor

        from qwen_vl_utils import process_vision_info
        self._process_vision_info = process_vision_info

        self.model_path = pretrained
        self.model = AutoModelForCausalLM.from_pretrained(
            self.model_path,
            torch_dtype=torch_dtype,
            device_map=device_map,
            trust_remote_code=trust_remote_code,
        )
        self.processor = AutoProcessor.from_pretrained(
            self.model_path,
            trust_remote_code=trust_remote_code,
        )
        self.processor.tokenizer.padding_side = "left"

    # ------------------------------------------------------------------
    # Conversation helpers
    # ------------------------------------------------------------------

    def generate_conversation_fn(self, text, image, role="user"):
        """
        Build the first turn. The system message is handled separately:
        dynamic_batch_manager prepends it, but we override it in
        append_item via the MEISSA_SYSTEM_PROMPT constant imported below.
        """
        messages = [
            {
                "role": role,
                "content": [
                    {"type": "image", "image": image},
                    {"type": "text", "text": text},
                ],
            }
        ]
        return messages

    def append_conversation_fn(self, conversation, text, image, role):
        if image:
            new_msg = {
                "role": role,
                "content": [
                    {"type": "image", "image": image},
                    {"type": "text", "text": text},
                ],
            }
        else:
            new_msg = {
                "role": role,
                "content": [{"type": "text", "text": text}],
            }
        conversation.append(new_msg)
        return conversation

    def getitem_fn(self, meta_data, idx):
        item = meta_data[idx]
        image = Image.open(item["image_path"])
        return dict(image=image, text=item["text"], idx=item["idx"])

    # ------------------------------------------------------------------
    # Batched generation
    # ------------------------------------------------------------------

    def form_input_from_dynamic_batch(self, batch: List[DynamicBatchItem]):
        if not batch:
            return None

        # Patch system prompt to Meissa's training prompt on every call
        for item in batch:
            if item.conversation and item.conversation[0].get("role") == "system":
                item.conversation[0]["content"] = MEISSA_SYSTEM_PROMPT

        messages = [item.conversation for item in batch]
        texts = [
            self.processor.apply_chat_template(
                msg, tokenize=False, add_generation_prompt=True
            )
            for msg in messages
        ]
        image_inputs, _ = self._process_vision_info(messages)
        inputs = self.processor(
            text=texts,
            images=image_inputs,
            padding=True,
            return_tensors="pt",
        )
        return inputs.to(self.model.device)

    def generate(self, batch: List[DynamicBatchItem]):
        import time

        if not batch:
            return

        max_new_tokens = self.generation_config.get("max_new_tokens", 2048)

        t0 = time.time()
        inputs = self.form_input_from_dynamic_batch(batch)
        t1 = time.time()

        generated_ids = self.model.generate(**inputs, max_new_tokens=max_new_tokens)
        t2 = time.time()

        generated_ids_trimmed = [
            out_ids[len(in_ids):]
            for in_ids, out_ids in zip(inputs.input_ids, generated_ids)
        ]
        output_texts = self.processor.batch_decode(
            generated_ids_trimmed,
            skip_special_tokens=True,
            clean_up_tokenization_spaces=False,
        )
        t3 = time.time()

        for item, output_text in zip(batch, output_texts):
            item.model_response.append(output_text)
            # Strip think blocks before adding to conversation so the
            # model doesn't see its own chain-of-thought as context.
            clean_text = _strip_think_blocks(output_text)
            self.append_conversation_fn(item.conversation, clean_text, None, "assistant")

        for item in batch:
            print("idx", item.meta_data.get("idx"),
                  "len(model_response)=", len(item.model_response))
        print(f"time: form_input {t1-t0:.2f}s  generate {t2-t1:.2f}s  decode {t3-t2:.2f}s")
        for in_ids, out_ids in zip(inputs["input_ids"], generated_ids):
            print("gen_tokens", out_ids.numel() - in_ids.numel())
